test('HTML export is standalone and has the article body', async ({ page }) => {
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/')
  await page.getByRole('button', { name: '导出', exact: true }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: /下载 HTML 文件/ }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/\.html$/)
  const stream = await download.createReadStream()
  const chunks: Buffer[] = []
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk))
  const html = Buffer.concat(chunks).toString('utf-8')
  expect(html).toContain('<!doctype html>')
  expect(html).toContain('愿每一份认真写下的内容')
  await page.setContent(html)
  await page.getByRole('button', { name: '复制到公众号', exact: true }).click()
  await expect(page.locator('#copy-status')).toContainText('已复制')
  const copied = await page.evaluate(() => navigator.clipboard.readText())
  expect(copied).toContain('愿每一份认真写下的内容')
  expect(copied).not.toContain('复制到公众号')
  expect(copied).not.toContain('在忙碌的日子里，找回阅读的节奏')
})

